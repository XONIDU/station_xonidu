function t(key) {
  const lang = (typeof window !== "undefined" && window.XONIDU_I18N && window.XONIDU_I18N.LANG)
    ? window.XONIDU_I18N.LANG
    : (typeof localStorage !== "undefined" ? localStorage.getItem("xonidu-lang") || "es" : "es");
  const dict = XONIDU_I18N_DATA[lang] || XONIDU_I18N_DATA.es;
  return dict[key] || key;
}

function applyLang() {
  // Traduce todos los elementos con data-i18n
  if (typeof document === "undefined") return;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    el.textContent = t(key);
  });
  // Traduce placeholders con data-i18n-placeholder
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    el.placeholder = t(key);
  });
  // Traduce títulos con data-i18n-title
  document.querySelectorAll("[data-i18n-title]").forEach(el => {
    const key = el.getAttribute("data-i18n-title");
    el.title = t(key);
  });
  // Traduce aria-label con data-i18n-aria
  document.querySelectorAll("[data-i18n-aria]").forEach(el => {
    const key = el.getAttribute("data-i18n-aria");
    el.setAttribute("aria-label", t(key));
  });
  document.documentElement.lang = (typeof window !== "undefined" && window.XONIDU_I18N && window.XONIDU_I18N.LANG) || "es";
}
